SET SQL DIALECT 3;
SET NAMES UTF8;

CREATE DATABASE 'localhost:C:\ERP\dados\FINANCEIRO.FDB'
  USER 'SYSDBA' PASSWORD 'masterkey'
  PAGE_SIZE 16384
  DEFAULT CHARACTER SET UTF8 COLLATION UNICODE_CI_AI;

/*
 * Título a receber, um por venda (ID_VENDA único = idempotência do POST /api/titulos).
 * Situação: ABERTO -> QUITADO | CANCELADO  (VENCIDO é derivado: ABERTO com vencimento passado)
 */
CREATE TABLE TITULO (
  ID                   INTEGER GENERATED BY DEFAULT AS IDENTITY,
  ID_VENDA             INTEGER       NOT NULL,
  CLIENTE_NOME         VARCHAR(100)  NOT NULL,
  CLIENTE_DOCUMENTO    VARCHAR(18)   NOT NULL,
  CLIENTE_EMAIL        VARCHAR(120),
  VALOR                NUMERIC(15,2) NOT NULL,
  DATA_EMISSAO         TIMESTAMP     NOT NULL,
  DATA_VENCIMENTO      TIMESTAMP     NOT NULL,
  DATA_RECEBIMENTO     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL, /* chegada do Vendas */
  STATUS               VARCHAR(10)   DEFAULT 'ABERTO' NOT NULL,
  DATA_PAGAMENTO       TIMESTAMP,
  VALOR_PAGO           NUMERIC(15,2),
  FORMA_PAGAMENTO      VARCHAR(30),
  DATA_CANCELAMENTO    TIMESTAMP,
  MOTIVO_CANCELAMENTO  VARCHAR(200),
  CONSTRAINT PK_TITULO PRIMARY KEY (ID),
  CONSTRAINT UK_TITULO_VENDA UNIQUE (ID_VENDA),
  CONSTRAINT CK_TITULO_STATUS CHECK (STATUS IN ('ABERTO', 'QUITADO', 'CANCELADO')),
  CONSTRAINT CK_TITULO_VALOR CHECK (VALOR > 0)
);

/*
 * Outbox: notificações ao ERP Vendas (quitação/cancelamento), gravadas na mesma
 * transação da operação e enviadas em segundo plano com retentativas.
 */
CREATE TABLE NOTIFICACAO_FILA (
  ID                   INTEGER GENERATED BY DEFAULT AS IDENTITY,
  ID_TITULO            INTEGER       NOT NULL,
  ID_VENDA             INTEGER       NOT NULL,
  TIPO                 VARCHAR(20)   NOT NULL,   /* QUITACAO | CANCELAMENTO */
  STATUS               VARCHAR(12)   DEFAULT 'PENDENTE' NOT NULL,
  TENTATIVAS           INTEGER       DEFAULT 0 NOT NULL,
  ULTIMO_ERRO          VARCHAR(1000),
  DATA_CRIACAO         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PROXIMA_TENTATIVA    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  DATA_PROCESSAMENTO   TIMESTAMP,
  CONSTRAINT PK_NOTIFICACAO_FILA PRIMARY KEY (ID),
  CONSTRAINT FK_NOTIFICACAO_TITULO FOREIGN KEY (ID_TITULO) REFERENCES TITULO (ID) ON DELETE CASCADE,
  CONSTRAINT CK_NOTIFICACAO_TIPO CHECK (TIPO IN ('QUITACAO', 'CANCELAMENTO')),
  CONSTRAINT CK_NOTIFICACAO_STATUS CHECK (STATUS IN ('PENDENTE', 'PROCESSADO', 'ERRO'))
);

CREATE INDEX IX_TITULO_STATUS ON TITULO (STATUS);
CREATE INDEX IX_TITULO_EMISSAO ON TITULO (DATA_EMISSAO);
CREATE INDEX IX_TITULO_VENCIMENTO ON TITULO (DATA_VENCIMENTO);
CREATE INDEX IX_NOTIFICACAO_PENDENTE ON NOTIFICACAO_FILA (STATUS, PROXIMA_TENTATIVA);

COMMIT;
